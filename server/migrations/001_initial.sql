CREATE TABLE IF NOT EXISTS users (
  id CHAR(36) PRIMARY KEY, username VARCHAR(32) NOT NULL UNIQUE, display_name VARCHAR(40) NOT NULL,
  password_hash VARCHAR(256) NOT NULL, created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
  token_hash CHAR(64) PRIMARY KEY, user_id CHAR(36) NOT NULL, expires_at DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE, INDEX (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pets (
  id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, name VARCHAR(40) NOT NULL,
  species ENUM('dog','cat','other') NOT NULL DEFAULT 'dog', breed VARCHAR(80) NOT NULL DEFAULT '', birthday DATE NULL,
  gender ENUM('unknown','male','female') NOT NULL DEFAULT 'unknown', notes TEXT NOT NULL, avatar_asset_id CHAR(36) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE, INDEX (user_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS assets (
  id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, pet_id CHAR(36) NOT NULL, name VARCHAR(150) NOT NULL,
  kind ENUM('photo','sprite') NOT NULL, action ENUM('idle','happy','walk','sleep') NULL,
  file_key VARCHAR(80) NOT NULL UNIQUE, mime_type VARCHAR(40) NOT NULL, byte_size INT UNSIGNED NOT NULL,
  width INT UNSIGNED NOT NULL, height INT UNSIGNED NOT NULL, frames INT UNSIGNED NOT NULL DEFAULT 1, job_id CHAR(36) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE CASCADE, INDEX (user_id, pet_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS generation_jobs (
  id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, pet_id CHAR(36) NOT NULL, reference_asset_id CHAR(36) NULL,
  status ENUM('queued','running','completed','partial','failed') NOT NULL DEFAULT 'queued',
  completed INT NOT NULL DEFAULT 0, total INT NOT NULL DEFAULT 4, error VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE CASCADE,
  FOREIGN KEY (reference_asset_id) REFERENCES assets(id) ON DELETE SET NULL, INDEX (user_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS memories (
  id CHAR(36) PRIMARY KEY, user_id CHAR(36) NOT NULL, pet_id CHAR(36) NOT NULL, title VARCHAR(100) NOT NULL,
  content TEXT NOT NULL, happened_on DATE NOT NULL, asset_id CHAR(36) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE CASCADE,
  FOREIGN KEY (asset_id) REFERENCES assets(id) ON DELETE SET NULL, INDEX (user_id, happened_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS desktop_profiles (
  user_id CHAR(36) PRIMARY KEY, pet_id CHAR(36) NULL, size INT NOT NULL DEFAULT 240, enabled BOOLEAN NOT NULL DEFAULT TRUE,
  idle_asset_id CHAR(36) NULL, happy_asset_id CHAR(36) NULL, walk_asset_id CHAR(36) NULL, sleep_asset_id CHAR(36) NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (pet_id) REFERENCES pets(id) ON DELETE SET NULL,
  FOREIGN KEY (idle_asset_id) REFERENCES assets(id) ON DELETE SET NULL,
  FOREIGN KEY (happy_asset_id) REFERENCES assets(id) ON DELETE SET NULL,
  FOREIGN KEY (walk_asset_id) REFERENCES assets(id) ON DELETE SET NULL,
  FOREIGN KEY (sleep_asset_id) REFERENCES assets(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
